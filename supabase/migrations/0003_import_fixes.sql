-- 0003_import_fixes: align the schema with the real product data before import. Run after 0002.
-- Findings from the data: allowedLotSize is fractional (0.01 for 16,872 of 17,546 products),
-- allergens come as CONTAINS / MAY_CONTAIN, embeddings are baai/bge-m3 (1024 dims).

-- the search view depends on products columns: drop, alter, recreate (comments and grants included)
drop view if exists wholesaler.v_product_search;

alter table wholesaler.products alter column allowed_lot_size type numeric;
alter table wholesaler.products alter column embedding type extensions.vector(1024);
comment on column wholesaler.products.embedding is 'Embedding of search_text. Model = EMBED_MODEL = baai/bge-m3 (1024 dims). Query embeddings must use the same model.';
comment on column wholesaler.products.allergens_contains is 'GS1 allergen codes declared CONTAINS or MAY_CONTAIN. Both count for allergens_none.';
alter table wholesaler.products add column if not exists unit_label text;
comment on column wholesaler.products.unit_label is 'Human size of one sales unit, e.g. "1 l", "2 x 10 l", "400 g". Display only.';

alter table wholesaler.order_lines alter column quantity_units type numeric;

create view wholesaler.v_product_search as
select
  p.id                    as product_id,
  p.name_en,
  p.name_fi,
  p.brand,
  p.vendor_name,
  p.category_code,
  cl.label                as category_name,
  p.sales_unit,
  p.unit_volume_l,
  p.unit_weight_kg,
  p.allowed_lot_size,
  p.temperature_condition,
  p.country_of_origin,
  p.claims,
  p.allergens_contains,
  p.labels,
  p.delivery_reliability,
  p.co2_kg_per_kg,
  exists (select 1 from wholesaler.product_substitutions s where s.product_id = p.id) as has_substitutes
from wholesaler.products p
left join wholesaler.code_labels cl on cl.kind = 'category' and cl.code = p.category_code
where not p.deleted;

comment on view wholesaler.v_product_search is 'The ONLY relation generated SQL may read. Deleted products are already filtered out. Join wholesaler.hybrid_rank(:q_text, :q_emb, :k) on product_id for ranking.';
comment on column wholesaler.v_product_search.product_id is 'Product id (int). Use it for prices, availability and orders.';
comment on column wholesaler.v_product_search.name_en is 'Product name in English. May be NULL.';
comment on column wholesaler.v_product_search.name_fi is 'Product name in Finnish. May be NULL.';
comment on column wholesaler.v_product_search.brand is 'Brand name, e.g. Valio, Arla. Case as in source data.';
comment on column wholesaler.v_product_search.vendor_name is 'Supplier name. Filter with = ANY(CAST(:vendor_names AS text[])).';
comment on column wholesaler.v_product_search.category_code is 'Category code from source data, e.g. 10400. Filter with = ANY(CAST(:category_codes AS text[])).';
comment on column wholesaler.v_product_search.category_name is 'Human label for category_code, generated by an LLM. Display only, never filter on it.';
comment on column wholesaler.v_product_search.sales_unit is 'Unit the product is sold in, e.g. ST (piece), KI (carton). Quantities in orders count this unit.';
comment on column wholesaler.v_product_search.unit_volume_l is 'Volume of ONE sales unit in litres. NULL if not sold by volume. Filter with BETWEEN :unit_volume_min AND :unit_volume_max (or >= / <= when one bound).';
comment on column wholesaler.v_product_search.unit_weight_kg is 'Weight of ONE sales unit in kg. NULL if not sold by weight. Filter with :unit_weight_min / :unit_weight_max.';
comment on column wholesaler.v_product_search.allowed_lot_size is 'Order quantity must be a multiple of this (0.01 for most products, so fractional quantities are allowed). Never filter on it.';
comment on column wholesaler.v_product_search.temperature_condition is 'Storage temperature code. Filter with = ANY(CAST(:temperature AS text[])).';
comment on column wholesaler.v_product_search.country_of_origin is 'Country code of origin. Display only.';
comment on column wholesaler.v_product_search.claims is 'text[] of nutritionalClaim codes, e.g. FREE_FROM_LACTOSE, FREE_FROM_GLUTEN, VEGAN. All required: claims @> CAST(:claims_all AS text[]).';
comment on column wholesaler.v_product_search.allergens_contains is 'text[] of GS1 allergen codes the product CONTAINS or MAY_CONTAIN (e.g. AM milk, AW gluten cereals, AE eggs). Exclude with NOT (allergens_contains && CAST(:allergens_none AS text[])).';
comment on column wholesaler.v_product_search.labels is 'text[] of packaging labels. Display only.';
comment on column wholesaler.v_product_search.delivery_reliability is 'Share of on-time deliveries, 0 to 1. NULL = no data. Sort DESC NULLS LAST when sort = delivery_reliability.';
comment on column wholesaler.v_product_search.co2_kg_per_kg is 'Average kg CO2-eq per kg for the product group. NULL = no data. Sort ASC NULLS LAST when sort = co2.';
comment on column wholesaler.v_product_search.has_substitutes is 'True if the source data lists substitutes for this product.';

grant select on wholesaler.v_product_search to search_ro;

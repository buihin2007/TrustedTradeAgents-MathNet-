create or replace function wholesaler.hybrid_rank(q_text text, q_emb text, k int default 300)
returns table (product_id int, rrf_score float8)
language sql stable security definer
set search_path = wholesaler, extensions, pg_catalog
as $$
  with q as (
    select case when length(trim(coalesce(q_text, ''))) = 0 then null
                else to_tsquery('simple', array_to_string(
                       tsvector_to_array(to_tsvector('simple', q_text)), ' | '))
           end as tsq
  ), fts as (
    select p.id, row_number() over (order by ts_rank_cd(p.fts, q.tsq) desc) as r
    from products p, q
    where q.tsq is not null and not p.deleted and p.fts @@ q.tsq
    order by r limit k
  ), vec as (
    select s.id, row_number() over (order by s.dist) as r
    from (select p.id, p.embedding <=> q_emb::vector as dist
          from products p
          where q_emb is not null and p.embedding is not null and not p.deleted
          order by dist limit k) s
  )
  select coalesce(fts.id, vec.id)::int,
         (coalesce(1.0 / (50 + fts.r), 0) + coalesce(1.0 / (50 + vec.r), 0))::float8
  from fts full outer join vec on fts.id = vec.id
$$;
comment on function wholesaler.hybrid_rank(text, text, int) is
  'Reciprocal Rank Fusion of full-text (OR of terms) and vector (cosine) ranks, k per branch, RRF constant 50. q_emb = ''[0.1,0.2,...]'' or NULL for full-text only.';

-- ============================================================ read-only role for generated SQL

do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'search_ro') then
    create role search_ro nologin;
  end if;
end $$;
grant usage on schema wholesaler to search_ro;
grant usage on schema extensions to search_ro;
grant select on wholesaler.v_product_search to search_ro;
grant execute on function wholesaler.hybrid_rank(text, text, int) to search_ro;
revoke execute on function wholesaler.hybrid_rank(text, text, int) from public;
grant search_ro to current_user;
-- Executor: BEGIN READ ONLY; SET LOCAL ROLE search_ro; SET LOCAL statement_timeout = '2s'; <sql>; COMMIT;


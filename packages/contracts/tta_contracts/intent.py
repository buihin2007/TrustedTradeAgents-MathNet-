"""register_intent, get_facets, mandates, agent status."""
from datetime import date, datetime
from decimal import Decimal
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from .search import Criteria


class RegisterIntentRequest(BaseModel):
    """Called with the USER's JWT. The agent can only reference the returned intent_id."""
    model_config = ConfigDict(extra="forbid")
    request_text: str = Field(min_length=1, max_length=1000)  # buyer's original words
    criteria: Criteria
    quantity: float = Field(gt=0)
    quantity_unit: Literal["l", "kg", "pcs"]
    delivery_date: date


class Intent(BaseModel):
    intent_id: str
    org_id: str
    user_id: str
    request_text: str
    criteria: Criteria
    quantity: float
    quantity_unit: Literal["l", "kg", "pcs"]
    delivery_date: date
    created_at: datetime
    expires_at: datetime


class CodeLabel(BaseModel):
    code: str
    label: str | None
    derived: bool = False   # True = label generated by LLM, not from Valio Aimo data


class Facets(BaseModel):
    claims: list[CodeLabel]
    allergens: list[CodeLabel]
    categories: list[CodeLabel]
    temperatures: list[CodeLabel]
    sales_units: list[CodeLabel]


class MandateLimits(BaseModel):
    model_config = ConfigDict(extra="forbid")
    auto_limit_eur: Decimal = Decimal("150")     # <= this: agent may buy alone
    order_limit_eur: Decimal = Decimal("600")    # > this: blocked
    weekly_budget_eur: Decimal = Decimal("2000") # rolling 7 days, placed orders
    price_tolerance_pct: Decimal = Decimal("3")  # quote vs order-time price
    allow_substitution: bool = True              # False: substitutes are blocked, not held
    allowed_category_codes: list[str] | None = None


class Mandate(MandateLimits):
    model_config = ConfigDict(extra="ignore")
    mandate_id: str
    org_id: str
    agent_id: str
    version: int
    signed_by: str        # user id
    signed_at: datetime


class SetAgentStatusRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    agent_id: str
    status: Literal["active", "paused"]
